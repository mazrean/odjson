// TestRenderLayout pins the layout contract of the block builder: doc and
// body comments land where they were emitted, else branches share the
// closing brace's line, empty blocks and clauses print as gofmt prints them,
// and a struct or interface type stays on one line.
func TestRenderLayout(t *testing.T) {
	g := &generator{pkg: &analyzer.Package{Name: "p"}}
	x, m := id("x"), id("m")
	g.funcDecl([]string{"// F does things.", "// Twice."}, nil, "F",
		signature([]*ast.Field{field("m", mapType(id("string"), emptyStruct()))}, id("error")),
		func(b *block) {
			g.comment(b, "// leading", "// comment")
			g.emit(b, define(x, spread(id("append"), call(sliceType(id("byte")), nilV), str("ab"))))
			s := g.ifStmt(b, nil, bin(x, token.EQL, nilV), func(*block) {})
			s = g.elseIf(s, nil, id("ok"), func(b *block) {
				g.emit(b, ret(nilV))
			})
			g.elseBlock(s, func(b *block) {
				g.comment(b, "// inner")
				g.emit(b, assign(index(m, str("k")), composite(emptyStruct())))
			})
			g.switchStmt(b, x, func(sw *block) {
				g.caseClause(sw, []ast.Expr{nilV}, func(*block) {})
				g.defaultClause(sw, func(b *block) {
					g.emit(b, ret(nilV))
				})
			})
			g.emit(b, varDecl("i", typ("interface{}")))
			g.emit(b, assign(id("_"), id("i")))
			g.emit(b, ret(nilV))
		})
	g.varDeclTop([]string{"// V is a variable."}, "V", id("int"))

	got, err := g.render([]string{"// Code generated by test. DO NOT EDIT."}, []string{`"bytes"`, `js "encoding/json"`})
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	want := `// Code generated by test. DO NOT EDIT.

package p

import (
	"bytes"
	js "encoding/json"
)

// F does things.
// Twice.
func F(m map[string]struct{}) error {
	// leading
	// comment
	x := append([]byte(nil), "ab"...)
	if x == nil {
	} else if ok {
		return nil
	} else {
		// inner
		m["k"] = struct{}{}
	}
	switch x {
	case nil:
	default:
		return nil
	}
	var i interface{}
	_ = i
	return nil
}

// V is a variable.
var V int
`
	if string(got) != want {
		t.Errorf("rendered source differs\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

// TestEmitCopies checks that emitting an expression twice positions two
// independent copies, so a shared node never drags an earlier statement onto
// a later line.
func TestEmitCopies(t *testing.T) {
	g := &generator{}
	x := id("x")
	var b block
	g.emit(&b, assign(x, nilV))
	g.emit(&b, assign(x, nilV))
	first := b.list[0].(*ast.AssignStmt).Lhs[0].(*ast.Ident)
	second := b.list[1].(*ast.AssignStmt).Lhs[0].(*ast.Ident)
	if first == second || first == x || first.NamePos == second.NamePos {
		t.Errorf("emit shared the identifier: %v %v (source %v)", first.NamePos, second.NamePos, x.NamePos)
	}
	if x.NamePos != token.NoPos {
		t.Errorf("emit positioned the caller's node at %v", x.NamePos)
	}
}

// TestGenerateReportsBadType checks that a type expression the parser
// rejects comes back from Generate as an error rather than a panic.
func TestGenerateReportsBadType(t *testing.T) {
	pkg := &analyzer.Package{
		Name:    "p",
		Imports: analyzer.NewImports("example.com/p"),
		Structs: []*analyzer.StructInfo{{Name: "T", Expr: "not a type", Local: true}},
	}
	if _, err := Generate(pkg, Options{}); err == nil {
		t.Fatal("Generate accepted an unparsable type expression")
	}
}
