package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestRunVersion(t *testing.T) {
	if err := run([]string{"-version"}); err != nil {
		t.Fatalf("-version: %v", err)
	}
	if v := version(); v == "" {
		t.Error("version() returned an empty string")
	}
}

func TestRunRejectsOutputPath(t *testing.T) {
	err := run([]string{"-output", "sub/dir/out.go"})
	if err == nil {
		t.Fatal("expected an error for an -output containing a path separator")
	}
	if !strings.Contains(err.Error(), "-output") {
		t.Errorf("unexpected error: %v", err)
	}
}

func TestRunRejectsTypeWithSeveralPackages(t *testing.T) {
	err := run([]string{"-type", "Scalars", "./internal/testfixture/..."})
	if err == nil || !strings.Contains(err.Error(), "single package") {
		t.Fatalf("expected a single-package error, got %v", err)
	}
}

// TestRunGeneratesIntoPackage drives the CLI the way //go:generate does, on a
// throwaway package inside this module so that go/packages can resolve it.
func TestRunGeneratesIntoPackage(t *testing.T) {
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	dir, err := os.MkdirTemp(filepath.Join(wd, "internal"), "clitest")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(dir) })

	src := "package clitest\n\n// Item is the type under test.\ntype Item struct {\n\tID int `json:\"id\"`\n}\n"
	if err := os.WriteFile(filepath.Join(dir, "types.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}

	rel, err := filepath.Rel(wd, dir)
	if err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"./" + filepath.ToSlash(rel)}); err != nil {
		t.Fatalf("run: %v", err)
	}

	out, err := os.ReadFile(filepath.Join(dir, "odjson_gen.go"))
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	// The four interfaces are the whole output: nothing in the package has to
	// call odjson by name for the generated codec to be used.
	for _, want := range []string{
		"// Code generated by odjson. DO NOT EDIT.",
		"package clitest",
		"func (v Item) MarshalJSON()",
		"func (v *Item) UnmarshalJSON(",
		"func (v Item) MarshalJSONTo(",
		"func (v *Item) UnmarshalJSONFrom(",
	} {
		if !strings.Contains(string(out), want) {
			t.Errorf("generated file is missing %q", want)
		}
	}
}
